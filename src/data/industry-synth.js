const DEMAND = /(需求|意向|服务)$/

/** 从自然语言中提取行业主题（去掉指令词、目标人群、情态词） */
export function extractTopic(input) {
  let t = String(input || '').trim().replace(/[，。！？、,.!?\s]/g, '')
  if (!t) return ''
  const strip = (re) => {
    let prev
    do {
      prev = t
      t = t.replace(re, '').replace(/的$/, '')
    } while (t !== prev && t.length > 1)
  }
  strip(LEAD_CMD)
  strip(AUDIENCE)
  strip(DEMAND)
  strip(MODAL)
  strip(TARGET_PREFIX)
  // 去掉「宠物做殡葬」这类中间的动词，拼成完整行业名
  t = t.replace(MID_VERB, '$1')
  strip(VERB)
  strip(DEMAND)
  strip(MODAL)
  strip(/^的+/)
  if (!t) t = String(input || '').replace(LEAD_CMD, '').slice(0, 10)
  return t.slice(0, 12)
}

/* ---------- 确定性哈希 ---------- */
function hashStr(s) {
  let h = 5381
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0
  return Math.abs(h)
}
function seeded(seed) {
  let a = seed
  return () => {
    a |= 0
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}


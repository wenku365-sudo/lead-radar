export function understandTask(input) {
  const tpl = TASK_TEMPLATES.find((t) => t.match.test(input))
  const ind = tpl ? INDUSTRIES.find((i) => i.key === tpl.ind) : null

  // 没命中内置样本：实时分析行业主题与业务形态，合成一份专属行业数据并注册
  if (!tpl || !ind) {
    const dyn = registerIndustry(synthIndustry(input))
    return {
      input,
      target: `${dyn.name}相关需求`,
      industries: ['抖音', '小红书'],
      focus: dyn.keywords.slice(0, 7),
      searchKeywords: [...new Set([dyn.searchWord, ...(dyn.searches || [])])].slice(0, 3),
      matchWords: dyn.keywords,
      emoji: dyn.emoji,
      industryName: dyn.name,
      industryKey: dyn.key,
      generated: true,
      archetypeLabel: dyn.archetypeLabel,
      videos: 120 + Math.floor(Math.random() * 260),
      customers: Math.min(100, dyn.count + Math.floor(Math.random() * 5))
    }
  }

  // 老行业没配 searches 时，用去掉通用后缀的行业名派生搜索词，避免拿「怎么收费」去搜视频
  const baseName = ind.name.replace(/行业|服务|项目|门店|招商|教育|辅导|会所|养生|瘦身|咨询/g, '')
  return {
    input,
    target: tpl.target,
    industries: ['抖音', '小红书'],
    focus: tpl.focus,
    // 搜索关键词：用于在平台上搜索对标视频
    searchKeywords: [
      ...new Set([ind.searchWord, ...(ind.searches || [`${baseName}推荐`, `${baseName}怎么选`])])
    ].slice(0, 3),
    // 匹配词：评论内容命中任意一个即视为意向线索进入系统
    matchWords: [...new Set([...ind.keywords, ...tpl.focus])],
    emoji: ind.emoji,
    industryName: ind.name,
    industryKey: ind.key,
    generated: false,
    archetypeLabel: ind.archetypeLabel || '精选行业样本',
    videos: 180 + Math.floor(Math.random() * 300),
    customers: Math.min(100, ind.count + Math.floor(Math.random() * 8))
  }
}


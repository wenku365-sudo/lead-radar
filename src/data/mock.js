// 行业完整样本缓存：每个行业 50-100 条，ID 形如 `${key}-序号`，跨次调用稳定（幂等去重）
const FULL_CACHE = new Map()

/** 取某个行业的完整意向客户样本（50-100 条，确定性生成） */
export function getIndustryCustomers(key) {
  if (!key) return []
  if (FULL_CACHE.has(key)) return FULL_CACHE.get(key)
  const ind = INDUSTRY_MAP[key]
  const arr = ind
    ? generateCustomersFrom([ind], 1).map((c, i) => ({ ...c, id: `${ind.key}-${i + 1}` }))
    : []
  FULL_CACHE.set(key, arr)
  return arr
}

/** 生成全部客户数据（确定性）：每个行业先载入约 20 条，其余按行业渐进插入 */

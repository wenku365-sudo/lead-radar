// 按长度降序构造正则，保证「怎么收费」优先于「收费」
const kwRegex = new RegExp(
  '(' + [...KEYWORDS].sort((a, b) => b.length - a.length).join('|') + ')',
  'g'
)

/** 将文本中的关键词标红加粗（返回 JSX 数组用片段数组） */
export function splitKeywords(text) {
  const parts = []
  let last = 0
  let m
  kwRegex.lastIndex = 0
  while ((m = kwRegex.exec(text)) !== null) {
    if (m.index > last) parts.push({ t: text.slice(last, m.index), kw: false })
    parts.push({ t: m[0], kw: true })
    last = m.index + m[0].length
  }
  if (last < text.length) parts.push({ t: text.slice(last), kw: false })
  return parts
}

// ---------- 确定性伪随机 ----------
function mulberry32(seed) {
  let a = seed
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}


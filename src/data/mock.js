function timeAgo(rand, i) {
  const r = rand()
  if (r < 0.12) return `${1 + Math.floor(rand() * 55)} 分钟前`
  if (r < 0.35) return `${1 + Math.floor(rand() * 22)} 小时前`
  if (r < 0.55) return '昨天'
  if (r < 0.75) return `${2 + Math.floor(rand() * 4)} 天前`
  if (r < 0.9) return `${1 + Math.floor(rand() * 3)} 周前`
  return `${1 + Math.floor(rand() * 2)} 个月前`
}

// 给评论计算意向评分：命中关键词越多分越高
function scoreOf(text) {
  let hits = 0
  for (const kw of KEYWORDS) if (text.includes(kw)) hits++
  const base = 52 + hits * 14
  return Math.min(98, base + Math.floor(Math.random() * 6))
}

/** 生成全部客户数据（确定性） */
export function generateCustomers() {
  const customers = []
  let id = 1
  for (const ind of INDUSTRIES) {
    const rand = mulberry32(20260001 + ind.key.length * 7 + ind.count)
    for (let i = 0; i < ind.count; i++) {
      const comment = ind.comments[i % ind.comments.length]
      const score = Math.min(97, 50 + (comment.split(/[？?！!，,、]/).length * 7) + Math.floor(rand() * 26))
      const platform = rand() < 0.55 ? '抖音' : '小红书'
      const nick = NICKNAMES[(i * 7 + ind.count) % NICKNAMES.length] + (rand() < 0.3 ? '_' + (i % 97 + 10) : '')
      const video = ind.videos[i % ind.videos.length]
      const level = score >= 80 ? 'high' : score >= 60 ? 'mid' : 'low'
      customers.push({
        id: id++,
        nick,
        avatarColor: AVATAR_COLORS[(i + ind.count) % AVATAR_COLORS.length],
        platform,
        industry: ind.name,
        industryKey: ind.key,
        comment,
        score,
        level,
        time: timeAgo(rand, i),
        today: rand() < 0.18,
        srcVideo: video.title,
        srcAuthor: video.author,
        likes: Math.floor(rand() * 320),
        tags: [ind.tags[i % ind.tags.length], ind.tags[(i + 3) % ind.tags.length]],
        followed: false,
        later: false
      })
    }
  }
  return customers
}

/** 实时采集：生成一位新客户（用于「意向客户」页持续流入动效） */
export function makeLiveCustomer(opts = {}) {
  const ind =
    INDUSTRIES.find((i) => i.key === opts.industryKey) ||
    INDUSTRIES[Math.floor(Math.random() * INDUSTRIES.length)]

  // 若当前有搜索词，优先产出包含该词的评论，保证新数据落在筛选结果内
  let comment = null
  if (opts.q) {
    const pool = ind.comments.filter((c) => c.includes(opts.q))
    if (pool.length) comment = pool[Math.floor(Math.random() * pool.length)]
    else {
      const all = INDUSTRIES.flatMap((i) => i.comments.filter((c) => c.includes(opts.q)))
      if (all.length) comment = all[Math.floor(Math.random() * all.length)]
    }
  }
  if (!comment) comment = ind.comments[Math.floor(Math.random() * ind.comments.length)]

  let score
  if (opts.level === 'high') score = 81 + Math.floor(Math.random() * 17)
  else if (opts.level === 'mid') score = 61 + Math.floor(Math.random() * 18)
  else if (opts.level === 'low') score = 42 + Math.floor(Math.random() * 17)
  else score = 58 + Math.floor(Math.random() * 40)

  const level = score >= 80 ? 'high' : score >= 60 ? 'mid' : 'low'
  const platform = opts.platform || (Math.random() < 0.55 ? '抖音' : '小红书')
  const video = ind.videos[Math.floor(Math.random() * ind.videos.length)]
  const nick =
    NICKNAMES[Math.floor(Math.random() * NICKNAMES.length)] +
    (Math.random() < 0.45 ? '_' + (10 + Math.floor(Math.random() * 88)) : '')

  return {
    id: 'live-' + Date.now() + '-' + Math.floor(Math.random() * 9999),
    nick,
    avatarColor: AVATAR_COLORS[Math.floor(Math.random() * AVATAR_COLORS.length)],
    platform,
    industry: ind.name,
    industryKey: ind.key,
    comment,
    score,
    level,
    time: '刚刚',
    today: true,
    srcVideo: video.title,
    srcAuthor: video.author,
    likes: Math.floor(Math.random() * 260),
    tags: [
      ind.tags[Math.floor(Math.random() * ind.tags.length)],
      ind.tags[Math.floor(Math.random() * ind.tags.length)]
    ],
    followed: false,
    later: false,
    isNew: true
  }
}


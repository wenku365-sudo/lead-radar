export const INDUSTRY_MAP = Object.fromEntries(INDUSTRIES.map((i) => [i.key, i]))

/** 注册一个行业（幂等）；同一 key 只保留首次生成的版本 */
export function registerIndustry(ind) {
  if (!ind || !ind.key) return null
  if (!INDUSTRY_MAP[ind.key]) {
    INDUSTRY_MAP[ind.key] = ind
    INDUSTRIES.push(ind)
  }
  return INDUSTRY_MAP[ind.key]
}

